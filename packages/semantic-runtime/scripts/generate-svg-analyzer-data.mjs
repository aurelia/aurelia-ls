import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '../../..');
const sourcePath = resolve(repoRoot, 'aurelia/packages/runtime-html/src/observation/svg-analyzer.ts');
const outputPath = resolve(repoRoot, 'packages/semantic-runtime/src/observation/svg-analyzer-data.generated.ts');

// Aurelia's analyzer uses historical SVG property casing for these keys, but the HTML foreign-content parser does not
// adjust their DOM attribute names. Keep analyzer support while preserving the browser spelling used by AttrMapper.
const unadjustedRuntimeSvgAttributes = new Set([
  'contentscripttype',
  'contentstyletype',
  'externalresourcesrequired',
  'filterres',
]);
const noRuntimeNameExclusions = new Set();

const source = readFileSync(sourcePath, 'utf8');
const elementsBlock = between(
  source,
  'private readonly _svgElements',
  'private readonly _svgPresentationElements',
);

const elementAttributes = new Map();
const runtimeElementNames = new Map();
const runtimeAttributeNames = new Map();
const elementEntryPattern = /'([^']+)':\s*(?:o\('([^']*)'\)|createLookup<[^>]+>\(\))/g;
for (const match of elementsBlock.matchAll(elementEntryPattern)) {
  const runtimeElementName = match[1];
  const elementName = normalize(runtimeElementName);
  rememberRuntimeName(runtimeElementNames, runtimeElementName);
  const attrs = attributeSetFor(elementAttributes, elementName);
  for (const attr of words(match[2] ?? '')) {
    rememberRuntimeName(runtimeAttributeNames, attr);
    attrs.add(normalize(attr));
  }
}

const presentationElementNames = words(extractOCall(source, 'private readonly _svgPresentationElements'));
const presentationAttributeNames = words(extractOCall(source, 'private readonly _svgPresentationAttributes'));
for (const elementName of presentationElementNames) {
  rememberRuntimeName(runtimeElementNames, elementName);
}
for (const attributeName of presentationAttributeNames) {
  rememberRuntimeName(runtimeAttributeNames, attributeName);
}
const presentationElements = new Set(presentationElementNames.map(normalize));
const presentationAttributes = new Set(presentationAttributeNames.map(normalize));

const generated = `// @generated by packages/semantic-runtime/scripts/generate-svg-analyzer-data.mjs
// Source of truth: aurelia/packages/runtime-html/src/observation/svg-analyzer.ts
// Runtime-name projections additionally preserve the HTML foreign-content parser differential recorded by the generator.
// Do not edit by hand.

const svgElementAttributes = ${objectLiteralFromMap(elementAttributes)} as const;

const svgPresentationElements = ${arrayLiteral(presentationElements)} as const;

const svgPresentationAttributes = ${arrayLiteral(presentationAttributes)} as const;

const runtimeSvgElementNames = ${objectLiteral(runtimeElementNames, noRuntimeNameExclusions)} as Readonly<Record<string, string>>;

const runtimeSvgAttributeNames = ${objectLiteral(runtimeAttributeNames, unadjustedRuntimeSvgAttributes)} as Readonly<Record<string, string>>;

const svgElementAttributeLookup = new Map<string, ReadonlySet<string>>(
  Object.entries(svgElementAttributes).map(([elementName, attributes]) => [elementName, new Set(attributes)]),
);
const svgPresentationElementLookup = new Set<string>(svgPresentationElements);
const svgPresentationAttributeLookup = new Set<string>(svgPresentationAttributes);

export function isKnownSvgElement(tagName: string): boolean {
  return svgElementAttributeLookup.has(normalizeSvgKey(tagName));
}

export function isStandardSvgAttribute(tagName: string, attributeName: string): boolean {
  const normalizedTagName = normalizeSvgKey(tagName);
  const normalizedAttributeName = normalizeSvgKey(attributeName);
  return (
    svgPresentationElementLookup.has(normalizedTagName) && svgPresentationAttributeLookup.has(normalizedAttributeName)
  ) || (
    svgElementAttributeLookup.get(normalizedTagName)?.has(normalizedAttributeName) === true
  );
}

/** Browser DOM nodeName/localName spelling after HTML foreign-content adjustment. */
export function runtimeSvgElementName(tagName: string): string {
  const normalized = normalizeSvgKey(tagName);
  return runtimeSvgElementNames[normalized] ?? normalized;
}

/** Browser DOM attribute spelling after HTML foreign-content adjustment. */
export function runtimeSvgAttributeName(attributeName: string): string {
  const normalized = normalizeSvgKey(attributeName);
  return runtimeSvgAttributeNames[normalized] ?? normalized;
}

function normalizeSvgKey(value: string): string {
  return value.toLowerCase();
}
`;

writeFileSync(outputPath, generated);

function between(value, start, end) {
  const startIndex = value.indexOf(start);
  const endIndex = value.indexOf(end, startIndex);
  if (startIndex < 0 || endIndex < 0) {
    throw new Error(`Could not find source block between ${start} and ${end}`);
  }
  return value.slice(startIndex, endIndex);
}

function extractOCall(value, marker) {
  const startIndex = value.indexOf(marker);
  if (startIndex < 0) {
    throw new Error(`Could not find ${marker}`);
  }
  const rest = value.slice(startIndex);
  const match = /o\('([^']*)'\)/.exec(rest);
  if (match == null) {
    throw new Error(`Could not find o('...') call after ${marker}`);
  }
  return match[1];
}

function words(value) {
  return value.split(/\s+/).filter(Boolean);
}

function normalize(value) {
  return value.toLowerCase();
}

function rememberRuntimeName(names, value) {
  const normalized = normalize(value);
  const existing = names.get(normalized);
  if (existing != null && existing !== value) {
    if (existing === normalized) {
      names.set(normalized, value);
      return;
    }
    if (value === normalized) {
      return;
    }
    throw new Error(`Conflicting runtime SVG names for ${normalized}: ${existing}, ${value}`);
  }
  names.set(normalized, value);
}

function attributeSetFor(map, elementName) {
  let attrs = map.get(elementName);
  if (attrs == null) {
    attrs = new Set();
    map.set(elementName, attrs);
  }
  return attrs;
}

function objectLiteralFromMap(map) {
  const entries = [...map.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([elementName, attrs]) => `  ${JSON.stringify(elementName)}: ${arrayLiteral(attrs)}`);
  return `{\n${entries.join(',\n')}\n}`;
}

function objectLiteral(map, exclusions) {
  const entries = [...map.entries()]
    .filter(([key, value]) => key !== value && !exclusions.has(key))
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`);
  return `{\n${entries.join(',\n')}\n}`;
}

function arrayLiteral(values) {
  const sorted = [...values].sort((a, b) => a.localeCompare(b));
  return `[${sorted.map((value) => JSON.stringify(value)).join(', ')}]`;
}
